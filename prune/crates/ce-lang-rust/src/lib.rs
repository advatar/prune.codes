/// Collect some file-level identifier references from `use`/`pub use` and
/// `mod`/`pub mod` lines.
///
/// These refs are useful for graph-ish expansion even when the `use` statement
/// itself is not selected as a fragment. We attach them to a file-level
/// `ApiSummary` fragment (generated by `ce-core` at index time).
pub fn collect_file_level_refs(source: &str) -> Vec<String> {
    let mut out: HashSet<String> = HashSet::new();

    for raw in source.lines() {
        let mut line = raw.trim();
        if line.is_empty() {
            continue;
        }

        // Strip single-line comments.
        if let Some((before, _)) = line.split_once("//") {
            line = before.trim();
        }
        if line.is_empty() {
            continue;
        }

        // `use ...;` or `pub use ...;`
        if line.starts_with("use ") || line.starts_with("pub use ") {
            parse_use_like_line(line, &mut out);
            continue;
        }

        // `mod foo;` or `pub mod foo;`
        if line.starts_with("mod ") || line.starts_with("pub mod ") {
            let mut s = line.trim_end_matches(';').trim();
            if let Some(rest) = s.strip_prefix("pub ") {
                s = rest.trim();
            }
            if let Some(rest) = s.strip_prefix("mod ") {
                let rest = rest.trim();
                let ident = rest
                    .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                    .next()
                    .unwrap_or("")
                    .trim();
                if !ident.is_empty() {
                    out.insert(ident.to_string());
                }
            }
            continue;
        }
    }

    let mut v: Vec<String> = out.into_iter().collect();
    v.sort();
    v.truncate(128);
    v
}

fn parse_use_like_line(line: &str, out: &mut HashSet<String>) {
    let mut s = line.trim();
    s = s.trim_end_matches(';').trim();
    if let Some(rest) = s.strip_prefix("pub ") {
        s = rest.trim();
    }
    let Some(rest) = s.strip_prefix("use ") else {
        return;
    };
    s = rest.trim();

    // Remove common roots.
    while let Some(rest) = s
        .strip_prefix("crate::")
        .or_else(|| s.strip_prefix("self::"))
        .or_else(|| s.strip_prefix("super::"))
    {
        s = rest;
    }

    // Handle grouped imports: `foo::{A, B as C}`
    if let Some(brace) = s.find('{') {
        let prefix = s[..brace].trim().trim_end_matches("::").trim();
        let inside = s[brace..].trim();
        let inside = inside.trim_start_matches('{').trim_end_matches('}').trim();

        for part in inside.split(',') {
            let part = part.trim();
            if part.is_empty() {
                continue;
            }
            if part == "self" {
                if let Some(last) = prefix.split("::").filter(|t| !t.is_empty()).last() {
                    if last != "*" {
                        out.insert(last.to_string());
                    }
                }
                continue;
            }

            if let Some((lhs, rhs)) = part.split_once(" as ") {
                let lhs_last = lhs
                    .trim()
                    .split("::")
                    .filter(|t| !t.is_empty())
                    .last()
                    .unwrap_or("");
                let rhs_last = rhs
                    .trim()
                    .split("::")
                    .filter(|t| !t.is_empty())
                    .last()
                    .unwrap_or("");
                if !lhs_last.is_empty() && lhs_last != "*" {
                    out.insert(lhs_last.to_string());
                }
                if !rhs_last.is_empty() && rhs_last != "*" {
                    out.insert(rhs_last.to_string());
                }
                continue;
            }

            let last = part
                .split("::")
                .filter(|t| !t.is_empty())
                .last()
                .unwrap_or("")
                .trim();
            if !last.is_empty() && last != "*" {
                out.insert(last.to_string());
            }
        }
        return;
    }

    // Non-grouped import.
    if let Some((lhs, rhs)) = s.split_once(" as ") {
        let lhs_last = lhs
            .trim()
            .split("::")
            .filter(|t| !t.is_empty())
            .last()
            .unwrap_or("");
        let rhs_last = rhs
            .trim()
            .split("::")
            .filter(|t| !t.is_empty())
            .last()
            .unwrap_or("");
        if !lhs_last.is_empty() && lhs_last != "*" {
            out.insert(lhs_last.to_string());
        }
        if !rhs_last.is_empty() && rhs_last != "*" {
            out.insert(rhs_last.to_string());
        }
        return;
    }

    let last = s
        .split("::")
        .filter(|t| !t.is_empty())
        .last()
        .unwrap_or("")
        .trim();
    if !last.is_empty() && last != "*" {
        out.insert(last.to_string());
    }
}

impl RustAdapter {
    pub fn new() -> Result<Self> {
        let mut parser = Parser::new();
        parser.set_language(&tree_sitter_rust::LANGUAGE.into())?;
        Ok(Self { parser })
    }

    pub fn parse(&mut self, source: &str) -> Result<Tree> {
        self.parser
            .parse(source, None)
            .ok_or_else(|| anyhow::anyhow!("tree-sitter parse returned None"))
    }

    /// Extract fragments from a Rust source file.
    ///
    /// MVP behavior:
    /// - extracts top-level items (fn/struct/enum/trait/impl/mod/const/static/type)
    /// - also extracts methods inside impl blocks as separate fragments (granularity)
    ///
    /// Note: file-level API summaries are generated in a language-agnostic way
    /// by `ce-core::api_summary` at index time.
    pub fn extract_fragments(&self, path: &Path, source: &str, tree: &Tree) -> Vec<Fragment> {
        let root = tree.root_node();
        let bytes = source.as_bytes();

        let mut out: Vec<Fragment> = Vec::new();
        let mut cursor = root.walk();

        for item in root.named_children(&mut cursor) {
            // skip non-items
            if let Some(mut frags) = self.fragments_from_item(path, bytes, item) {
                out.append(&mut frags);
            }
        }

        out
    }

    fn fragments_from_item(&self, path: &Path, bytes: &[u8], node: Node) -> Option<Vec<Fragment>> {
        let mut out: Vec<Fragment> = Vec::new();

        // Top-level item
        if let Some(f) = self.fragment_from_node(path, bytes, node, None, None) {
            // If it's an impl, also extract methods inside
            if f.kind == FragKind::Impl {
                let impl_type = self
                    .impl_target_type(bytes, node)
                    .unwrap_or_else(|| "impl".to_string());
                out.push(f.clone());

                // Methods inside impl are usually function_item nodes under declaration_list
                let mut cursor = node.walk();
                for ch in node.named_children(&mut cursor) {
                    self.collect_impl_methods(path, bytes, ch, &impl_type, &mut out);
                }
                return Some(out);
            }

            out.push(f);
            return Some(out);
        }

        None
    }

    fn collect_impl_methods(
        &self,
        path: &Path,
        bytes: &[u8],
        node: Node,
        impl_type: &str,
        out: &mut Vec<Fragment>,
    ) {
        // Walk impl subtree and extract function_item nodes nested within.
        let mut cursor = node.walk();
        if node.kind() == "function_item" {
            // Heuristic: only treat direct declaration_list children as impl methods.
            if node.parent().map(|p| p.kind()) == Some("declaration_list") {
                if let Some(f) = self.fragment_from_node(
                    path,
                    bytes,
                    node,
                    Some(FragKind::Method),
                    Some(impl_type),
                ) {
                    out.push(f);
                }
            }
            return;
        }
        for ch in node.named_children(&mut cursor) {
            self.collect_impl_methods(path, bytes, ch, impl_type, out);
        }
    }

    fn fragment_from_node(
        &self,
        path: &Path,
        bytes: &[u8],
        node: Node,
        force_kind: Option<FragKind>,
        method_impl_type: Option<&str>,
    ) -> Option<Fragment> {
        let preamble = extract_preamble(bytes, node.start_byte());

        let (mut kind, mut symbol) = match node.kind() {
            "function_item" => (FragKind::Function, self.node_name(bytes, node)),
            "struct_item" => (FragKind::Struct, self.node_name(bytes, node)),
            "enum_item" => (FragKind::Enum, self.node_name(bytes, node)),
            "trait_item" => (FragKind::Trait, self.node_name(bytes, node)),
            "impl_item" => (FragKind::Impl, self.impl_name(bytes, node)),
            "mod_item" => (FragKind::Mod, self.node_name(bytes, node)),
            "const_item" => (FragKind::Const, self.node_name(bytes, node)),
            "static_item" => (FragKind::Static, self.node_name(bytes, node)),
            "type_item" => (FragKind::TypeAlias, self.node_name(bytes, node)),
            _ => return None,
        };

        // Apply forced kind (e.g. impl methods)
        if let Some(fk) = force_kind {
            kind = fk;
        }

        // Best-effort: mark test functions
        if kind == FragKind::Function && is_test_preamble(&preamble) {
            kind = FragKind::Test;
        }

        // If this is a method and we have an impl type, qualify the symbol.
        if kind == FragKind::Method {
            if let (Some(impl_ty), Some(name)) = (method_impl_type, symbol.as_deref()) {
                symbol = Some(format!("{}::{}", impl_ty.trim(), name.trim()));
            }
        }

        let span = Span {
            start_byte: node.start_byte(),
            end_byte: node.end_byte(),
            start_line: node.start_position().row as u32,
            start_col: node.start_position().column as u32,
            end_line: node.end_position().row as u32,
            end_col: node.end_position().column as u32,
        };

        let body = self
            .slice_utf8(bytes, span.start_byte, span.end_byte)
            .to_string();

        // Preamble lines (doc + attributes) immediately above the node.
        // We include these in the signature to preserve important context like `#[test]`.
        let signature_core = signature_from_body(&body);
        let signature = if preamble.is_empty() {
            signature_core
        } else {
            format!("{}\n{}", preamble, signature_core)
        };

        // Doc comments only (stored separately)
        let doc = preamble
            .lines()
            .filter(|l| l.trim_start().starts_with("///") || l.trim_start().starts_with("//!"))
            .collect::<Vec<_>>()
            .join("\n");

        // Unison-ish ids:
        // - content hash: normalized body
        // - ast hash: structural (sexp)
        let content_hash = hash_text_hex(&normalize_whitespace(&body));
        let ast_hash = hash_text_hex(&node.to_sexp());

        // retrieval text should be compact and semantic
        let retrieval_text = format!(
            "path: {}\nkind: {:?}\nsymbol: {}\n{}\n{}",
            path.display(),
            kind,
            symbol.clone().unwrap_or_default(),
            if doc.is_empty() {
                preamble.clone()
            } else {
                doc.clone()
            },
            signature
        );

        let refs = collect_identifiers(bytes, node);

        Some(Fragment {
            id: content_hash,
            ast_hash,
            file: PathBuf::from(path),
            kind,
            symbol,
            span,
            signature,
            body,
            doc,
            retrieval_text,
            refs,
        })
    }

    fn node_name(&self, bytes: &[u8], node: Node) -> Option<String> {
        if let Some(n) = node.child_by_field_name("name") {
            return n.utf8_text(bytes).ok().map(|s| s.to_string());
        }
        // fallback: scan for identifier
        let mut c = node.walk();
        for ch in node.named_children(&mut c) {
            match ch.kind() {
                "identifier" | "type_identifier" => {
                    return ch.utf8_text(bytes).ok().map(|s| s.to_string())
                }
                _ => {}
            }
        }
        None
    }

    fn impl_name(&self, bytes: &[u8], node: Node) -> Option<String> {
        // best-effort: first line of impl block
        let text = node.utf8_text(bytes).ok()?;
        Some(text.lines().next().unwrap_or("impl").trim().to_string())
    }

    fn impl_target_type(&self, bytes: &[u8], node: Node) -> Option<String> {
        // Best-effort extraction of the impl target type.
        // tree-sitter-rust names the field "type" for impl_item.
        if let Some(ty) = node.child_by_field_name("type") {
            return ty.utf8_text(bytes).ok().map(|s| s.trim().to_string());
        }
        // Fallback: parse from first line of `impl`.
        let first = self.impl_name(bytes, node)?;
        // e.g. "impl Foo" or "impl Trait for Foo" -> try to take last token
        let toks: Vec<&str> = first.split_whitespace().collect();
        toks.last().map(|s| s.to_string())
    }

    fn slice_utf8<'a>(&self, bytes: &'a [u8], start: usize, end: usize) -> &'a str {
        std::str::from_utf8(&bytes[start..end]).unwrap_or("")
    }
}

/// Extract contiguous preamble lines immediately above a start byte.
///
/// We include both doc comments and attributes because they can contain
/// important semantic information for an agent (e.g. `#[test]`, `#[cfg]`, `#[inline]`).
fn extract_preamble(bytes: &[u8], start_byte: usize) -> String {
    let s = std::str::from_utf8(bytes).unwrap_or("");
    let prefix = &s[..start_byte.min(s.len())];
    let mut lines: Vec<&str> = prefix.lines().collect();
    let mut keep: Vec<String> = Vec::new();
    let mut started = false;

    while let Some(line) = lines.pop() {
        let trimmed = line.trim_start();
        if trimmed.is_empty() {
            if started {
                break;
            }
            continue;
        }
        if trimmed.starts_with("///") || trimmed.starts_with("//!") || trimmed.starts_with("#[") {
            started = true;
            keep.push(trimmed.to_string());
            continue;
        }
        break;
    }

    keep.reverse();
    keep.join("\n")
}

fn is_test_preamble(preamble: &str) -> bool {
    let lower = preamble.to_ascii_lowercase();
    // Try to avoid matching `#[cfg(test)]` on modules by requiring the attribute
    // name to end with `test` (common forms)
    lower.contains("#[test]")
        || lower.contains("#[tokio::test")
        || lower.contains("#[async_std::test")
        || lower.contains("::test")
}

/// Signature heuristic: take up to N lines or until '{' or ';'.
fn signature_from_body(body: &str) -> String {
    let mut sig = String::new();
    for (i, line) in body.lines().enumerate() {
        sig.push_str(line);
        sig.push('\n');
        if line.contains('{') || line.contains(';') || i >= 20 {
            break;
        }
    }
    sig
}

/// Collect identifiers inside a node subtree (best-effort, cheap).
fn collect_identifiers(bytes: &[u8], node: Node) -> Vec<String> {
    let mut out = HashSet::new();
    let mut cursor = node.walk();
    collect_identifiers_rec(bytes, node, &mut cursor, &mut out);
    let mut v: Vec<String> = out.into_iter().collect();
    v.sort();
    v
}

fn collect_identifiers_rec(
    bytes: &[u8],
    node: Node,
    cursor: &mut tree_sitter::TreeCursor,
    out: &mut HashSet<String>,
) {
    let kind = node.kind();
    if matches!(
        kind,
        "identifier"
            | "type_identifier"
            | "scoped_identifier"
            | "scoped_type_identifier"
            | "field_identifier"
    ) {
        if let Ok(t) = node.utf8_text(bytes) {
            let t = t.trim();
            if !t.is_empty() && t.len() <= 128 {
                // Always store the full token.
                out.insert(t.to_string());

                // For scoped paths like `foo::Bar`, also store the tail segment (`Bar`).
                // This makes ref→def resolution and incremental edge rebuilds more robust,
                // because definitions are often stored under the unqualified name.
                if matches!(kind, "scoped_identifier" | "scoped_type_identifier") {
                    if let Some(tail) = t.rsplit("::").next() {
                        let tail = tail.trim();
                        if !tail.is_empty() && tail.len() <= 128 && tail != t {
                            out.insert(tail.to_string());
                        }
                    }
                }
            }
        }
    }
    // Recurse
    if node.child_count() == 0 {
        return;
    }
    let mut c = node.walk();
    for ch in node.named_children(&mut c) {
        collect_identifiers_rec(bytes, ch, cursor, out);
    }
}

